export function createGridFromPreset(preset: MapPreset): {
  grid: CellState[][];
  homeDock: GridCoord;
} {
  const grid: CellState[][] = [];
  let homeDock: GridCoord = { ...preset.homeDock };

  for (let y = 0; y < preset.height; y++) {
    const row: CellState[] = [];
    const line = preset.asciiLayout[y] || '';
    for (let x = 0; x < preset.width; x++) {
      const ch = line[x] || '#';
      const isBorder =
        x === 0 || y === 0 || x === preset.width - 1 || y === preset.height - 1;
      const isWall = isBorder || ch === '#';
      if (ch === 'D') {
        homeDock = { x, y };
      }
      row.push({
        x,
        y,
        groundTruth: isWall ? 'WALL' : 'EMPTY',
        belief: 'UNKNOWN', // Zero preloaded map: 100% UNKNOWN at start
        logOdds: 0,
        inflationCost: 0,
        isFrontier: false,
        isDeadEndTaboo: false,
        deadEndClusterId: null,
        visitCount: 0,
        lastScannedTick: null,
      });
    }
    grid.push(row);
  }

  for (let dy = -1; dy <= 1; dy++) {
    for (let dx = -1; dx <= 1; dx++) {
      const nx = homeDock.x + dx;
      const ny = homeDock.y + dy;
      if (nx > 0 && ny > 0 && nx < preset.width - 1 && ny < preset.height - 1) {
        grid[ny][nx].groundTruth = 'EMPTY';
      }
    }
  }

  return { grid, homeDock };
}

export function cloneGrid(grid: CellState[][]): CellState[][] {
  return grid.map((row) => row.map((cell) => ({ ...cell })));
}
